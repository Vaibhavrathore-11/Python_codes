''' remove() method removes the first
matching element from the list'''

list = [1,2,3,4,5,6,2]
list.remove(2)

print(list)
#[1, 3, 4, 5, 6, 2] output



#pop() method removes the element at the specified position

num = [1,2,3,4,5,6]
num.pop(4)
print(num)


# example of pop()

a = [10,20,30]
a.pop()
print(a)# automatically removes the last element of the list